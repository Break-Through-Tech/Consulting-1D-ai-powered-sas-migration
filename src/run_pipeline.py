"""Run Programs 0, 1, and 2 using saved, reviewed Gemini-generated code.

This connects the three programs by passing their generated datasets and
required macro variables forward, rather than using SAS reference outputs
between steps. After execution, all 10 outputs are compared against the
original SAS results, with the reports saved in a separate run folder.

This runs code that has already been generated; it does not call Gemini.
Generated Python is executed with exec() and is not sandboxed, so the saved
files must be reviewed before running the pipeline.

Usage:
    python -m src.run_pipeline --reviewed
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4

import pandas as pd

from src import data_io, validation_report
from src.orchestrate import (
    DEFAULT_GROUP_CONFIG,
    DEFAULT_MANIFEST,
    build_program1_plan,
    build_step_plan,
    load_measure_groups,
)
from src.program1_integration import run_reviewed_program1
from src.step_runner import SavedStepCode, run_steps_report


ROOT = Path(__file__).resolve().parent.parent

PROGRAM_OUTPUTS = {
    program: tuple(
        name.upper()
        for name, spec in data_io.OUTPUTS.items()
        if spec["program"] == program
    )
    for program in (0, 1, 2)
}


class PipelineRunError(RuntimeError):
    """Raised when the pipeline cannot safely continue."""


def _get_case_insensitive(mapping, name, *, stage):
    """Find a generated output or variable without using SAS reference data."""
    matches = [
        value
        for key, value in mapping.items()
        if str(key).upper() == name.upper()
    ]

    if len(matches) != 1:
        raise PipelineRunError(
            f"{stage}: expected exactly one generated {name!r}, "
            f"found {len(matches)}. "
            "The pipeline will not fall back to a SAS reference output."
        )

    return matches[0]


def _required_outputs(datasets, program):
    """Confirm that a program produced all its required output tables."""
    outputs = {}

    for name in PROGRAM_OUTPUTS[program]:
        frame = _get_case_insensitive(
            datasets,
            name,
            stage=f"Program {program}",
        )

        if not isinstance(frame, pd.DataFrame):
            raise PipelineRunError(
                f"Program {program}: {name} is not a pandas DataFrame."
            )

        outputs[name] = frame

    return outputs


def _require_step_success(result, program):
    """Stop the pipeline if a step failed or was blocked."""
    bad = [
        step
        for step in result["steps"]
        if step["status"] in ("failed", "blocked")
    ]

    if bad:
        first = bad[0]

        raise PipelineRunError(
            f"Program {program}: {len(bad)} failed or blocked steps. "
            f"First: {first['id']} ({first['status']}): "
            f"{first.get('error')}. "
            "See the individual step report before retrying."
        )


def _program1_outputs(folder):
    """Load the five output tables generated by Program 1."""
    outputs = {}

    for name in PROGRAM_OUTPUTS[1]:
        path = folder / f"{name}.csv"

        if not path.is_file():
            raise PipelineRunError(
                f"Program 1: no generated output at {path}."
            )

        table = pd.read_csv(
            path,
            dtype={"PROVIDER_ID": "string"},
        )

        if "PROVIDER_ID" not in table.columns:
            raise PipelineRunError(
                f"Program 1: {name} has no PROVIDER_ID column."
            )

        table["PROVIDER_ID"] = table["PROVIDER_ID"].str.zfill(6)
        outputs[name] = table

    return outputs


def _program2_inputs(program0, program1, program0_vars, group_config):
    """Prepare Program 2 inputs from the generated Program 0 and 1 results.

    Program 0 provides the measure lists, while Program 1 provides the five
    group tables. We check that the columns match before passing the data
    and measure counts into Program 2.
    """
    datasets = {
        "STD_DATA_2025JUL_ANALYSIS": program0[
            "STD_DATA_2025JUL_ANALYSIS"
        ],
        **program1,
    }

    macro_vars = {}

    for group, config in group_config.items():
        var = f"measure_{group}"

        value = _get_case_insensitive(
            program0_vars,
            var,
            stage="Program 0 macro variables",
        )

        if not isinstance(value, str) or not value.strip():
            raise PipelineRunError(
                f"Program 0: {var} was not populated by generated code."
            )

        table_name = config["output_table"].upper()

        table = _get_case_insensitive(
            program1,
            table_name,
            stage="Program 1 output",
        )

        measures = [
            str(col)
            for col in table.columns
            if str(col).lower().startswith("std_")
        ]

        if not measures:
            raise PipelineRunError(
                f"Program 1: {table_name} has no standardized "
                "measure columns."
            )

        listed = value.split()

        if {name.lower() for name in measures} != {
            name.lower() for name in listed
        }:
            raise PipelineRunError(
                f"Program 1: {table_name} measure columns "
                f"do not match Program 0's {var}."
            )

        macro_vars[var] = value
        macro_vars[f"{var}_cnt"] = str(len(measures))

    return datasets, macro_vars


def _write_stage_status(run_dir, program, steps, counts=None):
    """Save the step results so failures can be reviewed later."""
    statuses = [
        {
            key: step.get(key)
            for key in (
                "id",
                "status",
                "error",
                "blocked_by",
                "stage",
            )
            if step.get(key) is not None
        }
        for step in steps
    ]

    summary = {
        "program": program,
        "steps": statuses,
    }

    if counts is not None:
        summary["counts"] = counts

    (run_dir / f"program{program}_steps.json").write_text(
        json.dumps(summary, indent=2) + "\n",
        encoding="utf-8",
    )


def _verify_saved_files(code_dirs, plans):
    """Check that all required reviewed code files are present."""
    for program in (0, 2):
        SavedStepCode(code_dirs[program]).check(plans[program])

    for step in plans[1]:
        if step["action"] == "translate":
            path = code_dirs[1] / f"{step['id']}.py"

            if not path.is_file():
                raise FileNotFoundError(
                    f"Program 1: missing reviewed code: {path}"
                )


# Check for obvious references to SAS answer files or handwritten baselines.
# This is an additional safeguard, not a sandbox or a substitute for review.
FORBIDDEN_IN_GENERATED_CODE = (
    "src.baseline",
    "data_io",
    "load_sas_output",
    "sas7bdat",
    "pyreadstat",
    "read_sas",
    "read_csv",
)


def _check_generated_code_is_standalone(code_dirs):
    """Flag saved code that may be reading SAS reference results."""
    problems = []

    for program in sorted(code_dirs):
        for path in sorted(Path(code_dirs[program]).glob("*.py")):
            source = path.read_text(encoding="utf-8")

            found = [
                word
                for word in FORBIDDEN_IN_GENERATED_CODE
                if word in source
            ]

            if found:
                problems.append(
                    f"Program {program}: {path.name} uses {found}"
                )

    if problems:
        raise PipelineRunError(
            "Generated code must only use the data "
            "the pipeline gives it: "
            + "; ".join(problems)
        )


def run_pipeline(*, code_dirs, run_dir, reviewed):
    """Run the three programs and return their results and validation report.

    All saved Python code must be reviewed before execution. This runs each
    program once; repeatability across generated runs is tracked under #66.
    """
    if reviewed is not True:
        raise PipelineRunError(
            "Read every generated Python file before running; "
            "then use --reviewed."
        )

    code_dirs = {
        program: Path(code_dirs[program])
        for program in (0, 1, 2)
    }

    plans = {
        0: build_step_plan(
            ROOT / "manifests" / "program0.json"
        ),
        1: build_program1_plan(
            DEFAULT_MANIFEST,
            DEFAULT_GROUP_CONFIG,
        ),
        2: build_step_plan(
            ROOT / "manifests" / "program2.json"
        ),
    }

    _verify_saved_files(code_dirs, plans)
    _check_generated_code_is_standalone(code_dirs)

    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=False)

    output_dir = run_dir / "data"
    output_dir.mkdir()

    # Program 0 starts with the original hospital input dataset.
    program0_result = run_steps_report(
        plans[0],
        code_dirs[0],
        reviewed=True,
        initial_datasets={
            "HC.ALLDATA_2025JUL": data_io.load_input(),
        },
    )

    _write_stage_status(
        run_dir,
        0,
        program0_result["steps"],
        program0_result.get("counts"),
    )

    _require_step_success(program0_result, 0)

    program0_outputs = _required_outputs(
        program0_result["datasets"],
        0,
    )

    for name, frame in program0_outputs.items():
        frame.to_csv(
            output_dir / f"{name}.csv",
            index=False,
            float_format="%.17g",
        )

    # Program 1 reads the standardized data generated by Program 0.
    program1_report = run_reviewed_program1(
        code_dir=code_dirs[1],
        input_csv=output_dir / "STD_DATA_2025JUL_ANALYSIS.csv",
        output_dir=output_dir,
        on_error="report",
    )

    _write_stage_status(
        run_dir,
        1,
        program1_report["steps"],
    )

    bad_program1 = [
        step
        for step in program1_report["steps"]
        if step["status"] in ("ERROR", "BLOCKED")
    ]

    if bad_program1:
        raise PipelineRunError(
            "Program 1: generated code failed or was blocked: "
            + ", ".join(step["id"] for step in bad_program1)
        )

    program1_outputs = _program1_outputs(output_dir)

    # Program 2 receives the generated group tables and required variables.
    program2_datasets, program2_vars = _program2_inputs(
        program0_outputs,
        program1_outputs,
        program0_result["macro_vars"],
        load_measure_groups(DEFAULT_GROUP_CONFIG),
    )

    program2_result = run_steps_report(
        plans[2],
        code_dirs[2],
        reviewed=True,
        initial_datasets=program2_datasets,
        initial_macro_vars=program2_vars,
    )

    _write_stage_status(
        run_dir,
        2,
        program2_result["steps"],
        program2_result.get("counts"),
    )

    _require_step_success(program2_result, 2)

    program2_outputs = _required_outputs(
        program2_result["datasets"],
        2,
    )

    for name, frame in program2_outputs.items():
        frame.to_csv(
            output_dir / f"{name}.csv",
            index=False,
            float_format="%.17g",
        )

    # SAS reference values are used only for the final comparisons.
    all_outputs = {
        **program0_outputs,
        **program1_outputs,
        **program2_outputs,
    }

    report = validation_report.build_report(
        all_outputs,
        f"reviewed Gemini chain in {run_dir}",
    )

    report_dir = run_dir / "validation"
    validation_report.save_report(report, report_dir)

    provenance = {
        "input": "original hospital input dataset",
        "program0_to_program1": (
            "generated STD_DATA_2025JUL_ANALYSIS.csv"
        ),
        "program1_to_program2": list(PROGRAM_OUTPUTS[1]),
        "program2_macro_vars": sorted(program2_vars),
        "code_dirs": {
            str(program): str(code_dirs[program])
            for program in (0, 1, 2)
        },
        "validation_status": report["status"],
        "validation_counts": report["counts"],
    }

    (run_dir / "handoff_summary.json").write_text(
        json.dumps(provenance, indent=2) + "\n",
        encoding="utf-8",
    )

    return {
        "report": report,
        "program0": program0_result,
        "program1": program1_report,
        "program2": program2_result,
        "data_dir": output_dir,
        "run_dir": run_dir,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=(
            "Run all three programs from reviewed Gemini-generated code"
        )
    )

    parser.add_argument(
        "--program0-code",
        type=Path,
        default=ROOT / "output/program0_generated_code",
    )

    parser.add_argument(
        "--program1-code",
        type=Path,
        default=ROOT / "output/program1_reviewed_code",
    )

    parser.add_argument(
        "--program2-code",
        type=Path,
        default=ROOT / "output/program2_generated_code",
    )

    parser.add_argument(
        "--run-dir",
        type=Path,
        help="new directory for this run; must not exist",
    )

    parser.add_argument(
        "--reviewed",
        action="store_true",
        help="confirm that all saved Python files were inspected",
    )

    args = parser.parse_args(argv)

    if not args.reviewed:
        parser.error(
            "read ALL three generated-code directories "
            "before running, then pass --reviewed"
        )

    run_dir = args.run_dir or (
        ROOT
        / "output/chain_runs"
        / (
            datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            + "_"
            + uuid4().hex[:8]
        )
    )

    try:
        result = run_pipeline(
            code_dirs={
                0: args.program0_code,
                1: args.program1_code,
                2: args.program2_code,
            },
            run_dir=run_dir,
            reviewed=True,
        )
    except (
        PipelineRunError,
        FileNotFoundError,
        FileExistsError,
    ) as error:
        parser.exit(
            1,
            f"Pipeline incomplete: {error}\n"
            f"Run folder (if created): {run_dir}\n",
        )

    print(validation_report.format_report(result["report"]))
    print(f"Saved generated outputs to {result['data_dir']}")
    print(f"Saved handoff summary and report to {result['run_dir']}")

    return 0 if result["report"]["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
