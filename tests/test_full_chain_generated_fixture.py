"""Verify the complete pipeline using saved, reviewed Gemini-generated code.

Program 0 starts with the original hospital data. Programs 1 and 2 use
the outputs generated by the earlier programs, without substituting SAS
reference tables. All 10 final outputs are validated against SAS.

No Gemini API calls are made during this test.
"""

import shutil
import tempfile
import unittest
from pathlib import Path

from src.run_pipeline import run_pipeline


ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures"


class FullChainOnGeneratedFixturesTests(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        super().setUpClass()

        temporary = tempfile.TemporaryDirectory()
        cls.addClassCleanup(temporary.cleanup)

        work_dir = Path(temporary.name)
        program1_code = work_dir / "program1_code"

        # Program 1 writes execution history beside its reviewed code.
        # Use a copy so the committed fixture remains unchanged.
        shutil.copytree(
            FIXTURES / "program1_generated",
            program1_code,
            ignore=shutil.ignore_patterns(
                ".translation_history",
                "translation_history.json",
            ),
        )

        cls.result = run_pipeline(
            code_dirs={
                0: FIXTURES / "program0_generated",
                1: program1_code,
                2: FIXTURES / "program2_generated",
            },
            run_dir=work_dir / "run",
            reviewed=True,
        )

    def test_all_ten_outputs_match_sas(self):
        report = self.result["report"]

        not_passing = {
            name: entry["status"]
            for name, entry in report["outputs"].items()
            if entry["status"] != "PASS"
        }

        self.assertEqual({}, not_passing)
        self.assertEqual(10, len(report["outputs"]))
        self.assertEqual(10, report["counts"]["PASS"])
        self.assertEqual("PASS", report["status"])

    def test_no_step_failed_or_was_blocked(self):
        for program in ("program0", "program2"):
            with self.subTest(program=program):
                counts = self.result[program]["counts"]

                self.assertEqual(0, counts["failed"])
                self.assertEqual(0, counts["blocked"])


if __name__ == "__main__":
    unittest.main()
